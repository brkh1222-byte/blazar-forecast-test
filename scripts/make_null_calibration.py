"""Collect the Part B numbers into one file and write the reproduction report.

Usage:  python scripts/make_null_calibration.py      (seconds; reads result files only)
Inputs: results/q0_kappa.csv, q0_verdicts.csv, partB_n1.csv, partB_n2.csv, power.csv,
        negative_control.csv, exploratory_X1.json, partB_summary.json, review_partB.json (optional)
Output: results/null_calibration.json   (task T3.5)
        results/reproduction.md         (task T2.2: differences from Peñil et al. Table A7)
"""
import json
from pathlib import Path

import pandas as pd

R = Path(__file__).resolve().parents[1] / "results"
kap = pd.read_csv(R / "q0_kappa.csv").set_index("rule")
q0 = pd.read_csv(R / "q0_verdicts.csv")
n1 = pd.read_csv(R / "partB_n1.csv")
n2 = pd.read_csv(R / "partB_n2.csv")
pw = pd.read_csv(R / "power.csv")
nc = pd.read_csv(R / "negative_control.csv").set_index("rule")
x1 = json.loads((R / "exploratory_X1.json").read_text())
summ = json.loads((R / "partB_summary.json").read_text())
CAND = [r for r in kap.index if r != "R0_as_printed"]
prim = n1[n1.cell == "primary-grid"].set_index("rule")

out = dict(
    source_files="q0_kappa.csv, partB_n1.csv, partB_n2.csv, power.csv, negative_control.csv, exploratory_X1.json",
    design=summ,
    authors=dict(hits=19, forecasts=59, rate=19 / 59),
    primary_rule=summ["primary_rule"],
    rules={},
    n1_robustness=dict(n_cells=int((n1.rule != "R0_as_printed").sum()),
                       min_p=float(n1[n1.rule != "R0_as_printed"].p_N1.min()),
                       max_p=float(n1[n1.rule != "R0_as_printed"].p_N1.max()),
                       cell_of_min=n1.loc[n1[n1.rule != "R0_as_printed"].p_N1.idxmin(),
                                          ["cell", "rule", "W", "n_min", "periods"]].to_dict()),
    exploratory_X1=x1,
)
for r in kap.index:
    d = dict(kappa=float(kap.loc[r, "kappa"]), agreement=float(kap.loc[r, "agreement"]),
             hits=int(kap.loc[r, "hits"]), evaluable=int(kap.loc[r, "evaluable"]),
             H_obs=float(prim.loc[r, "H_obs"]),
             N1=dict(mean=float(prim.loc[r, "H_null_mean"]), sd=float(prim.loc[r, "H_null_sd"]),
                     p=float(prim.loc[r, "p_N1"]), p_authors_19_of_59=float(prim.loc[r, "p_N1_authors"]),
                     delta_H=float(prim.loc[r, "H_obs"] - prim.loc[r, "H_null_mean"])))
    for m in ("PL", "BPL"):
        row = n2[(n2.model == m) & (n2.rule == r)].iloc[0]
        d[f"N2_{m}"] = dict(mean=float(row.H_null_mean), sd=float(row.H_null_sd), p=float(row.p_N2),
                            p_authors_19_of_59=float(row.p_N2_authors))
    if r in CAND:
        d["power"] = {str(a): float(p) for a, p in pw[pw.rule == r][["amplitude_sd", "power"]].values}
        d["negative_control_shift1_p"] = float(nc.loc[r, "p_N1"])
    out["rules"][r] = d
if (R / "review_partB.json").exists():
    out["review_exploratory"] = json.loads((R / "review_partB.json").read_text())
(R / "null_calibration.json").write_text(json.dumps(out, indent=2))

# ---------------------------------------------------------------- reproduction report
q0["source_supported"] = q0.groupby("source").supported.transform("sum")
lines = ["# Reproduction of Peñil et al. (2026) Table A7 (task T2.2)", "",
         "Generated by `scripts/make_null_calibration.py` from `results/q0_verdicts.csv`. Do not edit by hand.", "",
         "**Result: the published verdicts are NOT reproduced.** The rule as printed in their Sec. 8.1 (R0)",
         "supports every evaluable forecast. None of the four candidate rules fixed in advance reaches the",
         "pre-registered threshold of Cohen's kappa >= 0.7.", "",
         "| Rule | hits / evaluable | agreement with Table A7 (of 59) | kappa |", "|---|---|---|---|"]
for r in kap.index:
    lines.append(f"| {r} | {kap.loc[r,'hits']:.0f} / {kap.loc[r,'evaluable']:.0f} | "
                 f"{round(kap.loc[r,'agreement']*59):.0f} | {kap.loc[r,'kappa']:.2f} |")
lines += ["", f"Peñil et al.: 19 supported of 59. Ours: {int(kap.evaluable.iloc[0])} of 59 evaluable "
          "(a forecast needs at least 2 detected bins in its window; data cut at MJD 61000).", "",
          "## Known or possible reasons for the differences", "",
          "1. **The deciding step is not stated.** As printed, |t_obs − t_pred| ≤ max(60 d, 0.2T) is always true.",
          "2. **Period and reference epoch.** We take T from the spacing of the forecasts (or Table 1 for single",
          "   forecasts); the authors do not list the T used per source.",
          "3. **Data end date.** The paper says only \"17.3 years\"; we cut at MJD 61000 (2025-11-21).",
          "   Windows of forecasts in 2025-07 to 2025-12 are truncated in our data.",
          "4. **Month precision.** Forecast epochs are given to the month; we use day 15.",
          "5. **Light curves.** We use the public LCR light curves (30-day, fixed index, TS ≥ 4) as they are;",
          "   any extra processing by the authors is unknown.", "",
          "## Per-forecast verdicts (1 = supported)", "",
          "| Source | t_pred (MJD) | T (d) | Peñil | R1 | R2 | R3 | R4 | evaluable |", "|---|---|---|---|---|---|---|---|---|"]
for _, r in q0.iterrows():
    lines.append(f"| {r.source} | {r.t_pred:.0f} | {r.period_d:.0f} | {r.supported} | {r.R1_interior_max} | "
                 f"{r.R2_local_max} | {r.R3_high_state} | {r.R4_cycle_max} | {r.R1_interior_max_eval} |")
(R / "reproduction.md").write_text("\n".join(lines) + "\n")
print("wrote results/null_calibration.json and results/reproduction.md")
